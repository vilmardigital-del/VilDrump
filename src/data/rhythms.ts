import { DrumInstrument, Pattern16, StepHit } from '../audio/drumEngine';

export interface RhythmDefinition {
  id: string;
  name: string;
  category: 'Populares' | 'Nordeste' | 'Sul' | 'Samba & Pagode' | 'Gospel & Pop';
  defaultBpm: number;
  minBpm: number;
  maxBpm: number;
  swing?: number; // 0 to 0.35 subtle groove swing on off-16ths
  featured: boolean;
  ritmos: [Pattern16, Pattern16, Pattern16];
  viradas: [Pattern16, Pattern16, Pattern16];
  finalPattern: Pattern16;
}

const hit = (instrument: DrumInstrument, velocity = 1): StepHit => ({
  instrument,
  velocity,
});

function buildPattern(tracks: Partial<Record<DrumInstrument, number[]>>): Pattern16 {
  const steps: Pattern16 = Array.from({ length: 16 }, () => []);
  for (const [inst, velocities] of Object.entries(tracks)) {
    if (!velocities) continue;
    for (let i = 0; i < 16; i++) {
      const v = velocities[i] ?? 0;
      if (v > 0) {
        steps[i].push(hit(inst as DrumInstrument, v));
      }
    }
  }
  return steps;
}

